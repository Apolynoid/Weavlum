def rules_reference_text():
    """组装完整规则速查文本（供 build_system_prompt 拼装）。"""
    parts = []
    for _src, title, body in _SECTIONS:
        parts.append(_section(title, body))
    return "\n\n".join(parts)


def section_titles():
    """返回各节标题（测试与维护用）。"""
    return [title for _src, title, _body in _SECTIONS]
